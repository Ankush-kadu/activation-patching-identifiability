"""Check that the Paper-A snapshot is a faithful, self-contained copy of the project code.

For every snapshot script, the AST (with docstrings removed) is compared with the source file at the
recorded repository commit.  Any structural difference fails.  A differing string constant passes only
if it appears in WHITELIST exactly (file, old, new).  Comments are not part of the AST and may differ.

Also checks that every local import resolves inside the snapshot, and that no forbidden cross-paper
reference remains in the snapshot sources.

    python tools/check_snapshot.py            # exit 0 = pass
"""
import ast, os, re, subprocess, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))          # repro/
REPO = os.path.dirname(os.path.dirname(HERE))                                  # repository root
COMMIT = "ed345aef0b17a99a802561b6509b2fe27cda1790"

# (snapshot file, original string, snapshot string): the only non-docstring string edits allowed.
WHITELIST = {
    ("e0/edge_strength_matched.py", "prospective", None), ("e0/edge_strength_matched.py", "paper2", None),
    ("e0/edge_strength_matched.py", "claims.json", "claims_paperA.json"),
    ("e0/ofat_baseline.py", "paper", None), ("e0/ofat_baseline.py", "claims.py", "ledger_paperA.py"),
    ("e0/positive_control_heldout.py", "paper", None),
    ("e0/positive_control_heldout.py", "claims.py", "ledger_paperA.py"),
    ("e0/ratio_drivers.py", "prospective", None), ("e0/ratio_drivers.py", "paper2", None),
    ("e0/ratio_drivers.py", "claims.json", "claims_paperA.json"),
    ("e0/ratio_drivers.py", "paper", None), ("e0/ratio_drivers.py", "claims.py", "ledger_paperA.py"),
    ("e0/ratio_drivers.py",
     "every per-capture g ratio equals positive_control_heldout.json (rtol 1e-9); cell medians/counts equal "
     "prospective/paper2/claims.json predictM.* values",
     "every per-capture g ratio equals positive_control_heldout.json (rtol 1e-9); cell medians/counts equal "
     "claims_paperA.json predictM.* values"),
    ("e0/ratio_drivers.py",
     "ledger mpat (paper/claims.py), files carrying Zjm: 185 support-matched captures, 10 cells, 38 (cell, prompt) groups",
     "ledger mpat (ledger_paperA.py), files carrying Zjm: 185 support-matched captures, 10 cells, 38 (cell, prompt) groups"),
    ("ledger_paperA.py", "..", None),
    ("ledger_paperA.py", "...", None), ("ledger_paperA.py", "+", None), ("ledger_paperA.py", " more", None),
    ("ledger_paperA.py", "% GENERATED BY claims.py -- DO NOT EDIT BY HAND.",
     "% GENERATED BY ledger_paperA.py -- DO NOT EDIT BY HAND."),
    ("ledger_paperA.py", "% Regenerate: python claims.py ; verify: python claims.py --verify",
     "% Regenerate: python ledger_paperA.py ; verify: python ledger_paperA.py --verify"),
    ("ledger_paperA.py", "claims.json", "claims_paperA.json"),
    ("ledger_paperA.py", "claims.tex", "claims_paperA.tex"),
    ("ledger_paperA.py", None, "ledger_additions"), ("ledger_paperA.py", None, "ledger_additions.py"),
}
# Structural (non-string) edits allowed, described for the reader; verified by the per-file node diff below.
STRUCTURAL = {
    "e0/edge_strength_matched.py": "os.path.join(HERE, '..', 'prospective', 'paper2', 'claims.json') -> os.path.join(HERE, '..', 'claims_paperA.json')",
    "e0/ofat_baseline.py": "os.path.join('..', 'paper', 'claims.py') -> os.path.join('..', 'ledger_paperA.py')",
    "e0/positive_control_heldout.py": "os.path.join(dirname(__file__), '..', 'paper', 'claims.py') -> os.path.join(dirname(__file__), '..', 'ledger_paperA.py')",
    "e0/ratio_drivers.py": "two os.path.join targets repointed to the snapshot ledger (claims_paperA.json, ledger_paperA.py)",
    "ledger_paperA.py": "default E0 = ./e0 (one '..' removed); artifact lists not truncated (arts[:4] + [...] -> arts); a hook at the end of build() calls ledger_additions.extend(add, load_json, L) (new keys only)",
}
FORBIDDEN = re.compile(r"ICLR|paper2|prospective/|GPT-?6|reply ?\d+|review_r\d|meta-review|\bP3[01]\b|"
                       r"STUDY_REGISTRY|addendum|Supplement S\d|tab:transfer|tab:respfits|paper/claims\.py")


def strip_docstrings(tree):
    for n in ast.walk(tree):
        if isinstance(n, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and n.body \
                and isinstance(n.body[0], ast.Expr) and isinstance(getattr(n.body[0], "value", None), ast.Constant) \
                and isinstance(n.body[0].value.value, str):
            n.body = n.body[1:] or [ast.Pass()]
    return tree


def strings(tree):
    return [n.value for n in ast.walk(tree) if isinstance(n, ast.Constant) and isinstance(n.value, str)]


def blank_strings(tree):
    for n in ast.walk(tree):
        if isinstance(n, ast.Constant) and isinstance(n.value, str):
            n.value = "<S>"
    return tree


def original(rel):
    src = "paper/claims.py" if rel == "ledger_paperA.py" else rel
    r = subprocess.run(["git", "-C", REPO, "show", f"{COMMIT}:{src}"], capture_output=True, text=True)
    return r.stdout if r.returncode == 0 else None       # None: file is new in the snapshot


def main():
    files = ["ledger_paperA.py"] + sorted("e0/" + f for f in os.listdir(os.path.join(HERE, "e0")) if f.endswith(".py"))
    fails, report = [], []
    for rel in files:
        new_src = open(os.path.join(HERE, rel)).read()
        orig = original(rel)
        if orig is None:
            report.append(f"  new-in-snapshot              {rel} (import and reference checks only)")
            continue
        old_t, new_t = strip_docstrings(ast.parse(orig)), strip_docstrings(ast.parse(new_src))
        if ast.dump(old_t) == ast.dump(new_t):
            report.append(f"  identical-modulo-docstrings  {rel}")
            continue
        so, sn = strings(old_t), strings(new_t)
        removed = [s for s in so if s not in sn]
        added = [s for s in sn if s not in so]
        ok_removed = all((rel, s, None) in WHITELIST or any(w[0] == rel and w[1] == s for w in WHITELIST)
                         for s in removed)
        ok_added = all(any(w[0] == rel and w[2] == s for w in WHITELIST) for s in added)
        if rel not in STRUCTURAL and ast.dump(blank_strings(old_t)) != ast.dump(blank_strings(new_t)):
            fails.append(f"STRUCTURAL CHANGE NOT DECLARED: {rel}")
        if not (ok_removed and ok_added):
            fails.append(f"UNLISTED STRING EDIT in {rel}: removed={removed} added={added}")
        report.append(f"  documented-edit              {rel}: {STRUCTURAL.get(rel, 'string constants only')}")
    NEW_CODE = ["ledger_additions.py"] + sorted("tools/" + f for f in os.listdir(os.path.join(HERE, "tools"))
                                            if f.endswith(".py") and f != "check_snapshot.py")
    files = files + [f for f in NEW_CODE if os.path.exists(os.path.join(HERE, f))]   # new code: import + reference checks only
    local = {f[:-3] for f in os.listdir(os.path.join(HERE, "e0")) if f.endswith(".py")}
    project = {f[:-3] for f in os.listdir(os.path.join(REPO, "e0")) if f.endswith(".py")}
    for rel in files:
        for n in ast.walk(ast.parse(open(os.path.join(HERE, rel)).read())):
            names = [a.name for a in n.names] if isinstance(n, ast.Import) else \
                [n.module] if isinstance(n, ast.ImportFrom) and n.module and n.level == 0 else []
            for m in names:
                top = m.split(".")[0]
                if top in project and top not in local:
                    fails.append(f"IMPORT OUTSIDE SNAPSHOT: {rel} imports {top}")
        for i, line in enumerate(open(os.path.join(HERE, rel)), 1):
            if FORBIDDEN.search(line):
                fails.append(f"FORBIDDEN REFERENCE {rel}:{i}: {line.strip()[:120]}")
    print("\n".join(report))
    if fails:
        print(f"SNAPSHOT CHECK FAILED ({len(fails)})"); print("\n".join(fails)); sys.exit(1)
    print(f"SNAPSHOT CHECK OK — {len(files)} files; docstring/comment-only except the documented edits; "
          f"all local imports inside the snapshot; no forbidden references")


if __name__ == "__main__":
    main()
