"""Generate appendix_corrections.tex (Appendix A) from ../corrections_ledger.json.

Values come only from the ledger's recorded accepted_values / corrected_values; 'cause' and 'changed' are the
ledger's own text.  Refuses a display template with a typed decimal or k/n count, an unknown placeholder, or a
ledger entry without a template (and vice versa).

    python3 make_appendix_a.py
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from appendix_a_display import DISPLAY    # noqa: E402

LEDGER = os.path.join(HERE, "..", "corrections_ledger.json")
OUT = os.path.join(HERE, "appendix_corrections.tex")
PH = re.compile(r"\{([ac]):([A-Za-z]+)\}")
TYPED = re.compile(r"(?<![A-Za-z\d])(?:\d+\.\d+|\d+/\d+)")   # model names such as Qwen3.5 are allowed


def tex_escape(s):
    return (s.replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")
             .replace("#", r"\#").replace("$", r"\$").replace("~", r"\textasciitilde{}").replace("^", r"\^{}"))


def fill(tpl, acc, cor, eid):
    bad = TYPED.findall(PH.sub("", tpl))
    assert not bad, f"{eid}: typed number(s) {bad} in template {tpl!r}"
    out, pos = [], 0
    for m in PH.finditer(tpl):
        pre = tpl[pos:m.start()]
        out.append(pre)
        vals = acc if m.group(1) == "a" else cor
        assert m.group(2) in vals, f"{eid}: {m.group(0)} not recorded in the ledger entry"
        v = vals[m.group(2)]
        in_math = len(re.findall(r"(?<!\\)\$", "".join(out))) % 2 == 1
        out.append(v if in_math else f"${v}$")
        pos = m.end()
    out.append(tpl[pos:])
    return "".join(out)


def main():
    L = json.load(open(LEDGER))
    E = L["entries"]
    ids = [e["id"] for e in E]
    assert set(ids) == set(DISPLAY), (sorted(set(ids) ^ set(DISPLAY)))
    rows = []
    for e in E:
        item, a_tpl, c_tpl = DISPLAY[e["id"]]
        acc = fill(a_tpl, e["accepted_values"], e["corrected_values"], e["id"])
        cor = fill(c_tpl, e["accepted_values"], e["corrected_values"], e["id"])
        rows.append(f"{e['id']} & {item} & {acc} & {cor} & {tex_escape(e['cause'])} & "
                    f"{tex_escape(e['conclusion_changed'])} \\\\")
    body = "\n".join(rows)
    tex = rf"""% GENERATED by make_appendix_a.py from corrections_ledger.json -- do not edit by hand.
\section{{Correction log}}
\label{{app:corrections}}

The version submitted for review contained errors that we found after acceptance. Each
row below is one entry of a correction ledger ({len(E)} entries). For each entry the ledger records an independent
verification check appropriate to the correction (recomputation, mathematical checking or inspection) and, where
applicable, the source artifacts, scripts and cited files by hash and the command or inspection behind the
correction; associated review files record the adversarial verdicts. This table is generated from that ledger. The last column states
whether a scientific conclusion changed. All other numbers in this paper are the corrected ones.

{{\scriptsize
\setlength{{\tabcolsep}}{{3pt}}
\renewcommand{{\arraystretch}}{{1.15}}
\begin{{longtable}}{{@{{}}>{{\raggedright\arraybackslash}}p{{0.035\textwidth}}>{{\raggedright\arraybackslash}}p{{0.13\textwidth}}>{{\raggedright\arraybackslash}}p{{0.2\textwidth}}>{{\raggedright\arraybackslash}}p{{0.25\textwidth}}>{{\raggedright\arraybackslash}}p{{0.2\textwidth}}>{{\raggedright\arraybackslash}}p{{0.13\textwidth}}@{{}}}}
\toprule
id & item & accepted version & this version & cause & conclusion changed? \\
\midrule
\endfirsthead
\toprule
id & item & accepted version & this version & cause & conclusion changed? \\
\midrule
\endhead
{body}
\bottomrule
\end{{longtable}}
}}
"""
    open(OUT, "w").write(tex)
    print(f"wrote {OUT} ({len(E)} entries)")


if __name__ == "__main__":
    main()
